# 定义 AND、OR、XOR 逻辑门的使用场景和判断方法

LOGIC_GATE_RULES = """
## 逻辑门类型定义

### 1. OR 门（或门）
- **定义**：任意一个输入事件发生，输出事件就发生
- **符号**：半圆形，开口朝上
- **使用场景**：
  - 多种原因可能导致同一故障
  - 故障原因之间是"或"的关系
- **示例**：
  - 电机过热可能是：电源问题 OR 轴承故障 OR 绕组问题
  - 只要其中任何一个发生，电机就会过热

### 2. AND 门（与门）
- **定义**：所有输入事件同时发生，输出事件才发生
- **符号**：矩形
- **使用场景**：
  - 多个条件必须同时满足才导致故障
  - 故障原因之间是"且"的关系
- **示例**：
  - 泵无法正常工作：进口阀门关闭 AND 出口阀门关闭
  - 只有两个阀门同时关闭，泵才无法工作

### 3. XOR 门（异或门）
- **定义**：有且只有一个输入事件发生时，输出事件才发生
- **符号**：带加号的OR门
- **使用场景**：
  - 多个互斥的原因中只有一个会导致故障
  - 故障原因之间是"排他"的关系
- **示例**：
  - 电源缺相：A相缺 OR B相缺 OR C相缺（三种情况互斥）

## 逻辑门选择指南

### 判断使用 OR 门还是 AND 门？

**问题**：这个故障是"或"的关系还是"且"的关系？

**判断方法**：
- 如果问："是A导致的，还是B导致的？" → 使用 OR 门
- 如果问："是A和B同时导致的？" → 使用 AND 门

### 示例对比

**OR 门示例**：
- 问题：电机过热的原因有哪些？
- 答案：电源问题、轴承故障、绕组问题（任一都会导致过热）
- 结论：使用 OR 门

**AND 门示例**：
- 问题：什么情况下液压缸不动作？
- 答案：液压油压力不足 AND 电磁阀未通电（两个条件必须同时满足）
- 结论：使用 AND 门
"""
