# 事件类型判断规则
# 定义顶事件、中间事件、底事件的判断标准

EVENT_TYPE_RULES = """
## 事件类型定义

### 1. 顶事件（TOP）
- **定义**：用户指定的最终故障现象，是故障树的根节点
- **特征**：通常是一个完整的故障描述，包含故障对象和故障模式
- **示例**："电机过热"、"泵失效"、"阀门无法开启"

### 2. 中间事件（INTERMEDIATE）
- **定义**：介于顶事件和底事件之间的过渡事件，可以继续分解
- **特征**：有子节点，是故障传导路径上的中间环节
- **示例**："电源问题"、"轴承故障"、"密封失效"

### 3. 底事件（BASIC）
- **定义**：不可继续分解的根本原因事件，是故障树的叶子节点
- **特征**：无子节点，代表最基础的故障原因
- **示例**："电压不稳定"、"润滑不足"、"密封件老化"

## 事件类型判断规则

### 规则 1：层级位置判断
- 故障树的根节点一定是顶事件（TOP）
- 有子节点的事件通常是中间事件（INTERMEDIATE）
- 无子节点的事件通常是底事件（BASIC）

### 规则 2：故障原因判断
- 顶事件 = 故障现象（"什么坏了"）
- 中间事件 = 故障原因分类（"哪方面的问题"）
- 底事件 = 具体故障原因（"为什么坏了"）

### 规则 3：可分解性判断
- 如果一个事件还可以继续追问"为什么？"，则它是中间事件
- 如果已经追问到最底层（部件损坏、人为失误、环境因素），则是底事件

### 规则 4：因果链完整性
- 顶事件到每个底事件应该有一条完整的因果链
- 不应该有"跳跃"（如顶事件直接连接底事件，中间没有过渡）
"""
